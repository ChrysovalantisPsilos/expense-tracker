// Generates the Supabase Auth email templates in supabase/email-templates/
// from the shared branded layout (supabase/functions/_shared/email.ts), so
// they can never drift from the emails the edge functions send.
//
//   npm run emails:auth     rewrite the templates after changing the copy
//                           here or the layout in email.ts
//
// test/authEmails.test.js fails when a committed template differs from what
// this renders. The templates are pasted into the Supabase dashboard by hand
// (see supabase/email-templates/README.md).
//
// Supabase fills in Go template variables when it sends. brandEmail escapes
// every value, so the variables can't go through it as-is: the layout is
// rendered with plain sentinel URLs (which escaping leaves untouched) and the
// sentinels are swapped for the literal variables afterwards.
//
// The links point at our own site ({{ .SiteURL }}/auth/confirm with the
// token hash), never at Supabase's {{ .ConfirmationURL }} on supabase.co: a
// link to another domain than the sender's reads as phishing to spam filters.
// The app verifies the token there (src/features/auth/confirmLink.js).
import { writeFileSync } from 'node:fs'
import { pathToFileURL } from 'node:url'
import { brandEmail } from '../supabase/functions/_shared/email.ts'
import { confirmLinkTemplate } from '../src/features/auth/confirmLink.js'

const SITE_SENTINEL = 'https://site-url.invalid'
const LINK_SENTINEL = 'https://confirmation-url.invalid/'

// The button's link for a template, as it sits in HTML (both in href and as
// the "paste this link" text): the & between the parameters escaped.
export const confirmLinkHtml = (type) => confirmLinkTemplate(type).replaceAll('&', '&amp;')

const WHY = 'You’re getting this because this address was entered on Budgeer, a free hobby project.'

export const AUTH_EMAILS = [
  {
    template: 'Confirm signup',
    file: 'confirm-signup.html',
    subject: 'Confirm your email · Budgeer',
    type: 'signup',
    heading: 'Confirm your email',
    paragraphs: [
      'Welcome to Budgeer! Tap below to confirm your account and start tracking and splitting expenses.',
      'If you didn’t sign up, you can ignore this email — no account is created until you confirm.',
    ],
    button: 'Confirm email',
  },
  {
    template: 'Reset password',
    file: 'reset-password.html',
    subject: 'Reset your Budgeer password',
    type: 'recovery',
    heading: 'Reset your password',
    paragraphs: [
      'Someone (hopefully you) asked to reset the password for your Budgeer account. Tap below to choose a new one. The link works once and expires soon.',
      'If you didn’t ask for this, ignore this email — your password stays the same.',
    ],
    button: 'Choose a new password',
  },
  {
    template: 'Magic link',
    file: 'magic-link.html',
    subject: 'Your Budgeer sign-in link',
    type: 'magiclink',
    heading: 'Your sign-in link',
    paragraphs: [
      'Tap below to sign in to Budgeer. The link works once and expires soon.',
      'If you didn’t ask for it, ignore this email — no one can sign in without this link.',
    ],
    button: 'Sign in to Budgeer',
  },
]

// The paste-ready fragment for one template, with Supabase's variables.
export function renderAuthEmail(def) {
  const { fragment } = brandEmail({
    origin: SITE_SENTINEL,
    heading: def.heading,
    paragraphs: def.paragraphs,
    cta: { label: def.button, url: LINK_SENTINEL },
    showLink: true,
    footer: [WHY],
  })
  const body = fragment
    .split(SITE_SENTINEL).join('{{ .SiteURL }}')
    .split(LINK_SENTINEL).join(confirmLinkHtml(def.type))
  return `<!-- Generated by scripts/build-auth-emails.mjs from the shared layout in supabase/functions/_shared/email.ts. Don't edit by hand: change the copy in that script (or the layout in email.ts) and run npm run emails:auth. -->\n${body}`
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  for (const def of AUTH_EMAILS) {
    const out = new URL(`../supabase/email-templates/${def.file}`, import.meta.url)
    writeFileSync(out, renderAuthEmail(def))
    console.log(`wrote supabase/email-templates/${def.file}`)
  }
}
